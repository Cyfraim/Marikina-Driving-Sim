import assert from 'node:assert/strict';
import * as THREE from 'three';
import { Game } from '../src/game/Game.js';
import { Minimap } from '../src/ui/Minimap.js';
import { MissionSystem } from '../src/ui/MissionSystem.js';
import { satelliteGrid } from '../src/utils/satelliteGrid.js';
import { Weather } from '../src/world/Weather.js';
import { Vegetation } from '../src/world/Vegetation.js';
import { StreetObjects } from '../src/world/StreetObjects.js';
