const game = new Game();
game.scene = new THREE.Scene();
game.setupLighting();
game.vehicle = { position: new THREE.Vector3(2300, 2, -1800) };
game.updateShadows();
assert.deepEqual(game.sun.target.position.toArray(), [2300, 2, -1800]);
assert.deepEqual(game.sun.position.toArray(), [2400, 62, -1750]);
assert.equal(game.sun.shadow.camera.right - game.sun.shadow.camera.left, 150);
assert.equal(game.sun.shadow.camera.top - game.sun.shadow.camera.bottom, 150);
assert.equal(game.ambient.color.getHex(), 0xfff5e0);
assert.equal(game.sun.color.getHex(), 0xffe8b0);
game.weather = new Weather(game.scene);
game.setTimeOfDay('day');
assert.equal(game.scene.fog.color.getHex(), 0xc8d8e8);
game.weather.set('heavy');
game.applyAtmosphere();
assert.equal(game.scene.fog.far, 570);
game.setTimeOfDay('night');
assert.equal(game.scene.background.getHex(), 0x0a0a2a);
assert.equal(game.scene.fog.far, 180);
game.weather.set('clear');
game.applyAtmosphere();
assert.equal(game.scene.background.getHex(), 0x0a0a2a);
game.setTimeOfDay('day');
assert.equal(game.scene.fog.far, 950);
console.log('PASS shadows follow player with 150x150m frustum; afternoon/day/night/rain states remain consistent.');

const grid = satelliteGrid(700, -900);
assert.equal(grid.length, 9);
for (let row = 0; row < 3; row++) {
  assert.ok(Math.abs(grid[row * 3].maxX - grid[row * 3 + 1].minX) < 1e-7);
  assert.ok(Math.abs(grid[row * 3 + 1].maxX - grid[row * 3 + 2].minX) < 1e-7);
}
for (let i = 0; i < 6; i++) assert.ok(Math.abs(grid[i].maxZ - grid[i + 3].minZ) < 1e-7);
const minimap = Object.create(Minimap.prototype);
Object.assign(minimap, { satelliteTiles: [], gridCenter: null, gridLoading: false, gridRetryAt: 0, usingSatellite: false });
let requests = 0;
const options = { enabled: () => true, loadImage: async () => { requests++; return { naturalWidth: 640, naturalHeight: 640 }; } };
await minimap.refreshSatellite({ x: 700, z: -900 }, options);
assert.equal(requests, 9);
await minimap.refreshSatellite({ x: 1200, z: -900 }, options);
assert.equal(requests, 9);
await minimap.refreshSatellite({ x: 1201, z: -900 }, options);
assert.equal(requests, 18);
const previous = minimap.satelliteTiles;
await minimap.refreshSatellite({ x: 2000, z: -900 }, { enabled: () => true, loadImage: async () => null });
assert.equal(minimap.satelliteTiles, previous);
assert.equal(minimap.gridLoading, false);
const draws = [];
minimap.ctx = { drawImage: (...args) => draws.push(args) };
minimap.pxPerM = 0.2833;
minimap.drawSatellite({ position: { x: 1201, z: -900 } });
assert.equal(draws.length, 9);
assert.equal(draws[0][3], previous[0].maxX - previous[0].minX);
assert.equal(draws[0][1], previous[0].minX - 1201);
console.log('PASS satellite grid has shared seamless bounds, a >500m refresh threshold, atomic failure fallback, and metre-space draw sizes.');

const missions = Object.create(MissionSystem.prototype);
missions.group = new THREE.Group();
missions.beacons = [missions.makeBeacon(0, 0, 0xffdd00), missions.makeRing(20, 0, 0x33aaff)];
const records = [...missions.beacons];
let disposedGeometry = 0, disposedMaterial = 0;
missions.group.traverse(o => {
  o.geometry?.addEventListener('dispose', () => disposedGeometry++);
  o.material?.addEventListener('dispose', () => disposedMaterial++);
});
missions.clearMarkers();
assert.equal(disposedGeometry, 4);
assert.equal(disposedMaterial, 4);
assert.equal(missions.group.children.length, 0);
assert.equal(missions.beacons.length, 0);
for (const record of records) for (const key of ['mesh', 'cap', 'inner']) if (key in record) assert.equal(record[key], null);
missions.clearMarkers();
assert.equal(disposedGeometry, 4);
console.log('PASS mission cylinders, caps, outer and inner rings are removed, disposed and dereferenced; cleanup is idempotent.');
console.log('ALL PRIORITY 5 CHECKS PASSED');

const scene = new THREE.Scene();
const vegetation = new Vegetation(scene), objects = new StreetObjects(scene);
const bounds = { minX: 200, maxX: 600, minZ: 400, maxZ: 800 };
const treeGroup = new THREE.Group();
vegetation.build(bounds, treeGroup);
treeGroup.traverse(o => { if (o.isMesh) assert.equal(o.castShadow, false); });
const objectGroup = new THREE.Group();
objects.build(bounds, objectGroup);
assert.equal(objectGroup.children[0].castShadow, false);
assert.equal(objectGroup.children[1].castShadow, false);
assert.equal(objectGroup.children[2].castShadow, true);
assert.equal(objectGroup.children[3].castShadow, true);
assert.equal(objectGroup.children[4].castShadow, false);
const pedestrians = new PedestrianManager(scene);
pedestrians.group.traverse(o => { if (o.isMesh) assert.equal(o.castShadow, false); });
console.log('PASS streamed tree/canal/wire/furniture and pedestrian shadow exclusions; poles and parked vehicles cast shadows.');